const assert = require('assert'), crypto = require('crypto');
const { canonical, unchanged, envelope, compareSources } = require('../scripts/audit-mvp.cjs')._test;
const digest = value => crypto.createHash('sha256').update(canonical(value)).digest('hex');
const payload = { schema: 'fixture-v1', passed: false, numbers: [3, 1, 2] };
const valid = { schema: 't2-evidence-v1', kind: 'host', key: digest(payload), payload };
