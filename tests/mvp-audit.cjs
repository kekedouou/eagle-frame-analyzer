assert.throws(() => envelope({ ...valid, payload: { ...payload, passed: true } }, 'T2'), /digest/);
assert.throws(() => envelope(valid, 'T3'), /invalid/);
assert.throws(() => envelope({ ...valid, key: '0'.repeat(64) }, 'T2'), /digest/);
assert.strictEqual(canonical({ b: 1, a: { z: 3, y: 2 } }), '{"a":{"y":2,"z":3},"b":1}');
